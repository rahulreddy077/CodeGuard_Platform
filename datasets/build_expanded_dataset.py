def build_expanded_dataset():
    human_dir = os.path.join("datasets", "obfuscated_pairs", "human_independent")
    gpt_dir = os.path.join("datasets", "obfuscated_pairs", "ai_gpt35")

    os.makedirs(human_dir, exist_ok=True)
    os.makedirs(gpt_dir, exist_ok=True)

    # Write Independent Human Solutions
    for pname, code in HUMAN_INDEPENDENT_SOLUTIONS.items():
        fpath = os.path.join(human_dir, f"{pname}.py")
        with open(fpath, "w", encoding="utf-8") as f:
            f.write(code)

    # Write Multi-Generator GPT Solutions
    for pname, code in MULTI_GENERATOR_GPT_SOLUTIONS.items():
        fpath = os.path.join(gpt_dir, f"{pname}.py")
        with open(fpath, "w", encoding="utf-8") as f:
            f.write(code)

    # Build Complete Multi-Source Dataset Manifest
    sol_dir = os.path.join("datasets", "obfuscated_pairs", "solutions")
    ai_dir = os.path.join("datasets", "obfuscated_pairs", "ai_generated")

    rows = []

    # 1. Primary Human Solutions (Author 1)
    for fpath in sorted(glob.glob(os.path.join(sol_dir, "*.py"))):
        pname = os.path.basename(fpath).replace(".py", "")
        rows.append({
            "path": fpath.replace("\\", "/"),
            "problem_id": pname,
            "label": 0,
            "generator": "human",
            "author": "human_author_1"
        })

    # 2. Independent Human Solutions (Author 2)
    for fpath in sorted(glob.glob(os.path.join(human_dir, "*.py"))):
        pname = os.path.basename(fpath).replace(".py", "")
        rows.append({
            "path": fpath.replace("\\", "/"),
            "problem_id": pname,
            "label": 0,
            "generator": "human",
            "author": "human_author_2"
        })

    # 3. AI Generated CodeLlama Solutions
    for fpath in sorted(glob.glob(os.path.join(ai_dir, "*.py"))):
        pname = os.path.basename(fpath).replace(".py", "")
        rows.append({
            "path": fpath.replace("\\", "/"),
            "problem_id": pname,
            "label": 1,
            "generator": "codellama",
            "author": "codellama"
        })

    # 4. AI Generated GPT-3.5 Solutions
    for fpath in sorted(glob.glob(os.path.join(gpt_dir, "*.py"))):
        pname = os.path.basename(fpath).replace(".py", "")
        rows.append({
            "path": fpath.replace("\\", "/"),
            "problem_id": pname,
            "label": 1,
            "generator": "gpt35",
            "author": "gpt35"
        })

    manifest_df = pd.DataFrame(rows)
    manifest_path = "datasets/ai_dataset_manifest.csv"
    manifest_df.to_csv(manifest_path, index=False)

    print(f"Successfully expanded dataset manifest at {manifest_path}:")
    print(f"  Total Samples: {len(manifest_df)}")
    print(f"  Human Samples: {len(manifest_df[manifest_df['label'] == 0])} (Authors: human_author_1, human_author_2)")
    print(f"  AI Samples:    {len(manifest_df[manifest_df['label'] == 1])} (Generators: codellama, gpt35)")

if __name__ == "__main__":
    build_expanded_dataset()
